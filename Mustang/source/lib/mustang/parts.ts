export const PART_LIST = Object.values(PARTS);

export function partView(id: string, trans: "t5" | "4r70w"): PartInfo {
  const part = PARTS[id];
  if (!part) {
    return {
      id,
      name: "Unknown",
      system: "chassis",
      stage: 0,
      ex: [0, 0, 0],
      blurb: "",
      specs: [],
      fasteners: [],
      checks: [],
      keywords: [],
    };
  }
  if (part.alt && part.alt.when === trans) {
    return {
      ...part,
      name: part.alt.name,
      blurb: part.alt.blurb,
      specs: part.alt.specs,
      checks: part.alt.checks,
    };
  }
  return part;
}

export function searchParts(q: string): PartInfo[] {
  const query = q.trim().toLowerCase();
  if (!query) return [];
  const terms = query.split(/\s+/);
  return PART_LIST.filter((part) => {
    const hay = [
      part.name,
      part.blurb,
      part.system,
      part.alt?.name ?? "",
      part.alt?.blurb ?? "",
      ...part.keywords,
      ...part.specs.flatMap((s) => [s.label, s.value]),
      ...part.fasteners.flatMap((f) => [f.name, f.thread, f.torque ?? ""]),
      ...part.checks,
    ]
      .join(" ")
      .toLowerCase();
    return terms.every((term) => hay.includes(term));
  }).slice(0, 8);
}
