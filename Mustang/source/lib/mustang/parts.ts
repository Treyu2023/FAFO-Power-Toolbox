import type { Circuit, Fastener, PartInfo, Spec, System, Vec3 } from "./types";

type Seed = {
  id: string;
  name: string;
  system: System;
  stage: number;
  ex?: Vec3;
  parent?: string;
  circuit?: Circuit;
  blurb: string;
  specs?: Spec[];
  fasteners?: Fastener[];
  checks: string[];
  keywords?: string[];
  alt?: PartInfo["alt"];
};

function define(list: Seed[]): Record<string, PartInfo> {
  const out: Record<string, PartInfo> = {};
  for (const item of list) {
    out[item.id] = {
      id: item.id,
      name: item.name,
      system: item.system,
      stage: item.stage,
      ex: item.ex ?? [0, 0, 0],
      parent: item.parent,
      circuit: item.circuit,
      blurb: item.blurb,
      specs: item.specs ?? [],
      fasteners: item.fasteners ?? [],
      checks: item.checks,
      keywords: item.keywords ?? [],
      alt: item.alt,
    };
  }
  return out;
}

