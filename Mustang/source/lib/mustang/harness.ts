import type { Circuit } from "./types";
import { WIRES } from "./diagram";

export type Harness = {
  id: string;
  circuit: Circuit;
  radius: number;
  runs: [number, number, number][][];
};

const circuitOf = new Map(WIRES.map((w) => [w.id, w.circuit]));

function h(
  id: string,
  radius: number,
  runs: [number, number, number][][],
): Harness {
  return { id, circuit: circuitOf.get(id) ?? "power", radius, runs };
}

